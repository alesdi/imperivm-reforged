Point vec_of_angle(std::int32_t length, std::int32_t degrees) noexcept {
  std::int32_t d = degrees % 360;
  if (d < 0) d += 360;
  constexpr std::int64_t kOne = std::int64_t{1} << 30;
  const std::int64_t len = length;
  // `/` truncates toward zero, which is `_ftol`'s rounding.
  return Point{static_cast<std::int32_t>(len * kCosKQ30[d] / kOne),
               static_cast<std::int32_t>(len * kSinKQ30[d] / kOne)};
}

Point vec_by_dir(Point v, std::int32_t length) noexcept {
  const std::int64_t x = v.x;
  const std::int64_t y = v.y;
  const std::int64_t current = isqrt(x * x + y * y);
  // `0x0051b6de`: a zero-length input answers the square root in both
  // components, which is zero. See the header -- this is where `GetVecByDir`
  // and `point::SetLen` part company.
  if (current == 0) return Point{0, 0};
  return Point{static_cast<std::int32_t>(x * length / current),
               static_cast<std::int32_t>(y * length / current)};
}

bool on_left(Point a, Point b) noexcept {
  // 32-bit and wrapping, because `0x0051b15d` is `imul` and `sub` on 32-bit
  // registers and two map coordinates multiply to within a factor of two of
  // `INT32_MAX`. Unsigned arithmetic to get the wrap without the undefined
  // behaviour that signed overflow would be.
  const auto lhs = static_cast<std::uint32_t>(b.x) * static_cast<std::uint32_t>(a.y);
  const auto rhs = static_cast<std::uint32_t>(b.y) * static_cast<std::uint32_t>(a.x);
  return static_cast<std::int32_t>(lhs - rhs) > 0;
}

std::size_t heading_host_entry_count() noexcept { return kEntryCount; }

std::size_t register_heading_host(HostRegistry& registry) {
  std::size_t defined = 0;
  const auto free_fn = [&](std::string_view name, std::uint16_t arity, script::HostFn fn) {
    registry.define(CallKind::free_function, name, arity, fn);
    ++defined;
  };

  // Descending corpus call frequency, and all four are `data.pak` only.
  free_fn("GetVecByDir", 2, &fn_get_vec_by_dir);      // 17
  free_fn("GetVec", 3, &fn_get_vec);                  //  1
  free_fn("GetDirByAngle", 1, &fn_get_dir_by_angle);  // 16
  free_fn("OnLeft", 2, &fn_on_left);                  // 6
  free_fn("GetAngleByDir", 1, &fn_get_angle_by_dir);  // 4

  return defined;
}

