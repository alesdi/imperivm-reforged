/// `num * 2^30 >= den * tan_q30`, without overflowing.
///
/// The left side cannot exceed `2^61`, so a `den` large enough to push the
/// right side past that answers false without ever being multiplied.
///
/// **This guard is unreachable from any input the original answers sensibly,
/// and it is here anyway.** It bites at about 397,000 units, and the original's
/// own length is a 32-bit sum of two squares, which has already wrapped by
/// 46,341 -- so everything past that point is a vector whose `asin` argument
/// the original computes as greater than one and hands to the FPU. There is no
/// right answer up there to agree on. What there is, without this line, is a
/// signed multiply overflowing: undefined behaviour, which two builds need not
/// resolve the same way, in a function whose result reaches a hashed position.
/// A defined wrong answer is worth more than an undefined one. No test can
/// distinguish the two, and saying so here is better than leaving the line
/// looking measured.
[[nodiscard]] bool tangent_at_least(std::int64_t num, std::int64_t den,
                                    std::int64_t tan_q30) noexcept {
  constexpr std::int64_t kLimit = std::int64_t{1} << 61;
  if (tan_q30 != 0 && den > kLimit / tan_q30) return false;
  return num * kQ30One >= den * tan_q30;
}

/// `floor` and `ceil` of `t = asin(|y| / |v|) * 180/3.1415`, in degrees: the
/// angle off the **east** axis, folded into the first quadrant.
///
/// `asin(|y|/|v|)` is `atan(|y|/|x|)`, so `t >= d` is `|y| >= |x| * tan(d/K2)`.
///
/// `t` runs over `[0, 90.0027]` -- the top is not 90 because `asin(1)` times
/// `180/3.1415` overshoots by the 0.003 per cent the constant is wrong by -- so
/// the floor reaches 90 and the ceiling reaches 91, which is what the 91st
/// tangent entry is for.
///
/// **The ceiling is the floor plus one except at zero.** `t` is a whole number
/// only when `asin` is exactly zero, which is `y == 0`. Any other whole `t`
/// would need `|y|/|v|` -- an integer over a square root -- to be exactly the
/// sine of a whole degree. The original computes in doubles and could in
/// principle round onto a whole number where this does not; that residue is
/// one unit of one degree, on one of the two quadrants that subtract, and it is
/// the labelled divergence.
struct AsinDegrees {
  std::int32_t floor_deg;
  std::int32_t ceil_deg;
};

[[nodiscard]] AsinDegrees asin_degrees(Point v) noexcept {
  const std::int64_t ax = v.x < 0 ? -static_cast<std::int64_t>(v.x) : v.x;
  const std::int64_t ay = v.y < 0 ? -static_cast<std::int64_t>(v.y) : v.y;
  // The largest `d` whose tangent the vector still clears. Binary search rather
  // than a walk, because the answer is as often 89 as it is 1.
  std::int32_t low = 0;
  std::int32_t high = 90;
  while (low < high) {
    const std::int32_t mid = (low + high + 1) / 2;
    if (tangent_at_least(ay, ax, kTanQ30[mid])) {
      low = mid;
    } else {
      high = mid - 1;
    }
  }
  const bool whole = v.y == 0 && v.x != 0;
  return AsinDegrees{low, whole ? low : low + 1};
}

