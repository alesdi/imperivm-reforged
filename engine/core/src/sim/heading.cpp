std::int32_t angle_of_dir(Point v) noexcept {
  // `0x0051b74d` sums the two squares in **32 bits** and hands the result to
  // `fild`, with a `+2^32` fixup for a negative. The sum is what the original's
  // length test looks at, and it is zero exactly when the vector is; the wrap
  // needs a component above 46,340 to happen at all, which is past the largest
  // map, so it is reproduced by arithmetic rather than by branch.
  const auto ux = static_cast<std::uint32_t>(v.x);
  const auto uy = static_cast<std::uint32_t>(v.y);
  const std::uint32_t sum = ux * ux + uy * uy;
  if (sum == 0) return 0;

  const AsinDegrees t = asin_degrees(v);
  // The four quadrants, transcribed from `0x0051b7a8`: `a`, `6.283 - a`,
  // `3.1415 - a` and `3.1415 + a` -- the textbook repair of an angle off the
  // east axis. `(c - a) * K2` is one product in the original, and `c * K2` is
  // exactly 360 and exactly 180 in doubles for both of its constants, so
  // truncating the difference is subtracting the *ceiling*.
  if (v.x >= 0) return v.y >= 0 ? t.floor_deg : 360 - t.ceil_deg;
  return v.y >= 0 ? 180 - t.ceil_deg : 180 + t.floor_deg;
}

Point dir_of_angle(std::int32_t degrees) noexcept {
  std::int32_t d = degrees;
  if (d < kDirLow || d > kDirHigh) {
    // Reduced, and the header says what that costs. Arithmetic rather than a
    // loop: a script may pass any int, and a loop over `INT32_MAX / 360`
    // iterations is a hang rather than an answer.
    d = d % 360;
    if (d < 0) d += 360;
  }
  const auto index = static_cast<std::size_t>(d - kDirLow);
  return Point{kDirX[index], kDirY[index]};
}

