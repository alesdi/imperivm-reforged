#!/usr/bin/env python3
"""Generate the sine and cosine table `point::Rot` multiplies by.

    python3 tools/gen_rot_table.py > engine/core/src/sim/rot_table.inc

`point::Rot(d)` (0x00697d90 in `gbr.exe`) turns its whole-degree argument into
radians with one x87 multiply by the double 0x1.1df46a2506b91p-6 -- the double
nearest `3.1415926535 / 180`, pi cut at eleven digits -- and takes the FPU's
sine and cosine of the product. `docs/formats/point-rot.md` describes the whole routine.
This script computes, for every d in 0..360, the two values the FPU holds:

  * the angle, `d * K` rounded to a 53-bit significand, round-to-nearest-even:
    the multiply runs under the process's default precision control, 53 bits;
  * `sin` and `cos` of that angle, rounded to the x87's 64-bit significand,
    round-to-nearest-even. Precision control does not apply to the FPU's sine
    and cosine, so their results keep all 64 bits.

The trigonometry is done here, offline, in exact rational arithmetic (a Taylor
series on integers scaled by 2**400), so the engine needs no floating point.
Each value is emitted as a sign, a 64-bit significand with its top bit set (or
zero) and a binary exponent: value = sign * significand * 2**exponent.

**What this assumes.** That the FPU's sine and cosine return the correctly
rounded value of the true function at the rounded angle. The x87 reduces its
argument with a 66-bit approximation of pi, which shifts the two results near
180 and 360 degrees by about 1e-20 absolute; no truncation `Rot` makes can
move by that much, because the coordinate it multiplies is an integer under
2**31 and the sum it truncates is rounded to 53 bits first.

Standard library only; prints C++ to standard output.
"""
from fractions import Fraction

K_HEX = "0x1.1df46a2506b91p-6"
SCALE_BITS = 400


def round_significand(value: Fraction, bits: int) -> tuple[int, int, int]:
    """(sign, significand, exponent), the significand `bits` wide, nearest-even."""
    if value == 0:
        return 0, 0, 0
    sign = -1 if value < 0 else 1
    v = abs(value)
    # Find e with 2**(bits-1) <= v / 2**e < 2**bits.
    e = v.numerator.bit_length() - v.denominator.bit_length() - bits
    while v / Fraction(2) ** e >= 2 ** bits:
        e += 1
    while v / Fraction(2) ** e < 2 ** (bits - 1):
        e -= 1
    scaled = v / Fraction(2) ** e
    m = scaled.numerator // scaled.denominator
    rest = scaled - m
    if rest > Fraction(1, 2) or (rest == Fraction(1, 2) and m % 2 == 1):
        m += 1
    if m == 2 ** bits:
        m //= 2
        e += 1
    return sign, m, e


def as_fraction(sign: int, m: int, e: int) -> Fraction:
    return sign * Fraction(m) * Fraction(2) ** e


def sin_cos(a: Fraction) -> tuple[Fraction, Fraction, Fraction]:
    """sin(a) and cos(a) to within 2**-(SCALE_BITS-8), and that bound."""
    one = 1 << SCALE_BITS
    x = (a.numerator << SCALE_BITS) // a.denominator  # a, scaled
    s = 0
    c = 0
    term = one  # x**n / n!, scaled
    n = 0
    while term != 0:
        if n % 4 == 0:
            c += term
        elif n % 4 == 1:
            s += term
        elif n % 4 == 2:
            c -= term
        else:
            s -= term
        n += 1
        term = (term * x) // (one * n)
    scale = Fraction(one)
    return Fraction(s) / scale, Fraction(c) / scale, Fraction(1, 1 << (SCALE_BITS - 8))


def correctly_rounded(value: Fraction, bound: Fraction) -> tuple[int, int, int]:
    sign, m, e = round_significand(value, 64)
    # The rounding is decided only if the value's error bound cannot cross a tie.
    if m:
        for neighbour in (m - 1, m + 1):
            tie = (as_fraction(sign, m, e) + as_fraction(sign, neighbour, e)) / 2
            assert abs(value - tie) > bound, "a tie within the error bound"
    return sign, m, e


def main() -> None:
    k = Fraction(float.fromhex(K_HEX))
    assert float.fromhex(K_HEX) == 3.1415926535 / 180
    rows = []
    for d in range(361):
        a = as_fraction(*round_significand(d * k, 53))
        s, c, bound = sin_cos(a)
        rows.append((d, correctly_rounded(s, bound), correctly_rounded(c, bound)))
    print("// Generated by tools/gen_rot_table.py; do not edit. One row per whole degree")
    print("// 0..360: {sign, significand, exponent} of the sine, then of the cosine, at the x87's")
    print("// angle for that degree. value = sign * significand * 2^exponent.")
    for d, (ss, sm, se), (cs, cm, ce) in rows:
        print(f"    {{{{{ss}, 0x{sm:016x}u, {se}}}, {{{cs}, 0x{cm:016x}u, {ce}}}}},  // {d}")


if __name__ == "__main__":
    main()
